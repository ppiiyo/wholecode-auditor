"""Markdown report rendering."""
from .auditor import AuditResult

LEVEL_ICON = {"CRITICAL": "🔴", "WARNING": "🟡", "OK": "✅"}


def markdown(result: AuditResult) -> str:
    lines = [
        "# Wholecode Audit Report",
        "",
        f"**Repository:** `{result.repo}`  ",
        f"**Files analyzed:** {result.files_count:,} "
        f"({result.total_chars:,} chars, ~{result.total_chars // 4:,} tokens, "
        f"{result.chunks} chunk(s))  ",
        f"**Overall risk:** {result.overall_risk:.0%}  ",
        f"**Production ready: {'YES' if result.production_ready else 'NO'}**",
        "",
        "## Findings",
        "",
    ]
    for f in result.findings:
        lines.append(f"### {LEVEL_ICON[f.level]} {f.check.title} — {f.probability:.0%}")
        if f.probability >= 0.5:
            lines.append("")
            if f.locations:
                lines.append("Suspicious locations (pattern pre-screen):")
                for path, lineno, snippet in f.locations:
                    lines.append(f"- `{path}:{lineno}` — `{snippet}`")
            else:
                lines.append("_Model flagged this category; review manually "
                             "(no obvious pattern matches)._")
        lines.append("")

    clean = [f for f in result.findings if f.level == "OK"]
    if clean:
        lines += ["## Clean checks", "",
                  ", ".join(f"✅ {f.check.title}" for f in clean), ""]

    lines += ["---",
              "_Generated by wholecode-auditor · powered by SubQ Snap "
              "(384K-token context)_"]
    return "\n".join(lines)
